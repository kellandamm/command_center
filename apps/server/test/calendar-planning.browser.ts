import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { AddressInfo } from "node:net";
import { chromium, type Page } from "playwright";
import { CalendarWorkspace } from "../src/calendar/workspace";
import { NotesStore } from "../src/notes/store";
import { SettingsStore } from "../src/settings";
import { loadConfig } from "../src/config";
import { makeAuthenticator } from "../src/auth";
import { createApp } from "../src/http";
import { DailyBriefingService } from "../src/daily-briefing/service";
import { closeIntegrationServer, openIntegrationStores } from "./helpers";

async function status(page: Page, selector: string, text: string) {
  await page.waitForFunction(({ selector, text }) => document.querySelector(selector)?.textContent?.includes(text), { selector, text });
}

test("planning browser: real Board identity, keyboard schedule/reschedule/complete, conflicts and mobile inbox", { timeout: 90_000 }, async () => {
  const dir = await mkdtemp(join(tmpdir(), "cc-planning-browser-"));
  const cfg = loadConfig({ DATA_DIR: dir, ADMIN_TOKEN: "t".repeat(32), OWNER_EMAILS: "owner@example.com", TZ: "America/Chicago" });
  const integration = await openIntegrationStores(dir, cfg), notes = await NotesStore.open(dir);
  const calendar = await CalendarWorkspace.open(cfg, undefined, { notes, board: integration.board });
  const settings = new SettingsStore(dir); await settings.load();
  const dailyBriefing = await DailyBriefingService.open(dir, cfg.tz);
  const native = await calendar.create({ name: "Focus", kind: "native" });
  const server = createApp({ cfg, ...integration, notes, calendar, settings, dailyBriefing, auth: makeAuthenticator(cfg, async (jwt) => ({ email: jwt === "owner" ? "owner@example.com" : "reader@example.com" })) });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: "Pacific/Kiritimati", extraHTTPHeaders: { "cf-access-jwt-assertion": "owner" } });
    const page = await context.newPage(), errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, (route) => route.abort());
    await page.goto(base + "/calendar");
    await status(page, "#cal-task-status", "0 unscheduled");
    await page.locator("#cal-task-title").fill("Review task planning");
    await page.locator("#cal-task-title").press("Enter");
    await status(page, "#cal-task-status", "1 unscheduled");
    const task = integration.board.list()[0]!;
    assert.equal(task.title, "Review task planning");
    await page.getByRole("link", { name: "Plan / edit task", exact: true }).focus();
    await page.keyboard.press("Enter");
    await page.waitForSelector("#event-form:not([hidden])");
    assert.equal(await page.locator("#event-task").inputValue(), task.id);
    assert.equal(await page.locator("#event-calendar").inputValue(), native.id);
    assert.equal(await page.locator("#event-calendar option").count(), 1);
    await page.locator("#task-estimate").fill("45");
    await page.locator("#task-due").fill("2030-06-11");
    await page.locator("#task-priority").selectOption("high");
    await page.getByRole("button", { name: "Save task details", exact: true }).focus();
    await page.keyboard.press("Enter");
    await status(page, "#task-status", "Task details saved");
    await page.locator("#event-start").fill("2030-06-10T09:00");
    await page.locator("#event-duration").fill("45");
    await page.locator("#event-preview-options summary").focus();
    await page.keyboard.press("Enter");
    await page.getByRole("button", { name: "Preview availability", exact: true }).focus();
    await page.keyboard.press("Enter");
    await status(page, "#event-preview-status", "Preview only");
    assert.equal(calendar.store.events().length, 0);
    await page.getByRole("button", { name: "Save event", exact: true }).focus();
    await page.keyboard.press("Enter");
    await status(page, "#event-save-status", "Event saved");
    const first = calendar.store.events()[0]!;
    assert.equal(first.taskId, task.id);
    assert.equal(first.start, "2030-06-10T14:00:00.000Z");
    assert.equal(first.end, "2030-06-10T14:45:00.000Z");
    assert.equal(integration.board.get(task.id)?.estimatedMinutes, 45);
    assert.equal(integration.hobieQueue.list().length, 0);
    if (process.env.CALENDAR_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.CALENDAR_SCREENSHOT_DIR, "planning-editor-desktop.png"), fullPage: true });
    await page.goto(base + "/calendar");
    await status(page, "#cal-task-status", "0 unscheduled");
    await page.getByText("Scheduled tasks (1)", { exact: true }).click();
    await page.getByRole("link", { name: /Edit block:/ }).focus(); await page.keyboard.press("Enter");
    await page.waitForSelector("#event-form:not([hidden])");
    await page.locator("#event-start").fill("2030-06-11T10:00");
    await page.locator("#event-use-duration").check();
    await page.locator("#event-duration").fill("60");
    await page.getByRole("button", { name: "Save event", exact: true }).click();
    await status(page, "#event-save-status", "Event saved");
    assert.equal(calendar.store.events().length, 1);
    assert.equal(calendar.store.event(first.id)?.end, "2030-06-11T16:00:00.000Z");
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if (process.env.CALENDAR_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.CALENDAR_SCREENSHOT_DIR, "planning-editor-mobile.png"), fullPage: true });
    await page.getByRole("button", { name: "Complete task", exact: true }).focus(); await page.keyboard.press("Enter");
    await status(page, "#task-status", "Task completed");
    assert.equal(integration.board.get(task.id)?.column, "Done");
    assert.equal(integration.wins.list().filter((win) => win.ref === task.id).length, 1);
    assert.equal(calendar.store.events().length, 1);
    await page.goto(base + "/agent?view=board");
    await page.waitForSelector(".board-card");
    assert.equal(await page.locator(".board-card").count(), 1);
    assert.ok((await page.locator('.board-col[data-column="Done"]').textContent())?.includes(task.title));
    await page.goto(base + "/calendar/event?task=" + task.id);
    await page.waitForSelector("#event-form:not([hidden])");
    await page.locator("#task-title").fill("My unsaved task draft");
    integration.board.updateMeta(task.id, { title: "Changed elsewhere" });
    await page.getByRole("button", { name: "Save task details", exact: true }).click();
    await status(page, "#task-status", "changed elsewhere");
    assert.equal(await page.locator("#task-title").inputValue(), "My unsaved task draft");
    await page.getByRole("button", { name: "Save event", exact: true }).click();
    await status(page, "#event-save-status", "changed elsewhere");
    assert.equal(calendar.store.events().length, 1);
    await page.goto(base + "/calendar");
    await status(page, "#cal-task-status", "0 open Board tasks");
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if (process.env.CALENDAR_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.CALENDAR_SCREENSHOT_DIR, "planning-inbox-mobile.png"), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    if (process.env.CALENDAR_SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.CALENDAR_SCREENSHOT_DIR, "planning-inbox-desktop.png"), fullPage: true });
    await context.setExtraHTTPHeaders({ "cf-access-jwt-assertion": "ordinary" });
    await page.goto(base + "/calendar/event?event=" + first.id);
    await status(page, "#event-load-status", "configured owner");
    assert.equal(await page.locator("#event-form").isHidden(), true);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await closeIntegrationServer(server, integration); await rm(dir, { recursive: true, force: true }); }
});
